import { query } from '../config/db.js';
import { getSecurityHeatmap } from '../services/simulationService.js';

export async function listAlerts(req, res) {
  const result = await query('SELECT * FROM alerts ORDER BY created_at DESC LIMIT 50');
  return res.json({ alerts: result.rows, heatmap: getSecurityHeatmap() });
}

export async function createAttackSimulation(req, res) {
  const { title = 'Attack simulation triggered', severity = 'medium' } = req.body;
  const result = await query(
    'INSERT INTO alerts (title, severity, category, description) VALUES ($1, $2, $3, $4) RETURNING *',
    [title, severity, 'Simulation', 'Generated by the AI security monitoring lab']
  );

  return res.status(201).json({ alert: result.rows[0] });
}
